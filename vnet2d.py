"""
vnet2d.py

Envoltorio sobre monai.networks.nets.VNet para poder usarla como variante 2D
con los mismos 3 canales de entrada (DWI, ADC, FLAIR) que las otras 3
arquitecturas del TFM.

V-Net original es 3D (así aparece en el anteproyecto). Usar aquí spatial_dims=2
es una ADAPTACIÓN por tiempo de cómputo en Colab y uso compartido de
hiperparametros, con esta variante no se pone a prueba esa hipótesis,solo la
arquitectura V-Net en sí, sin contexto 3D).

Por qué el envoltorio (no basta con VNet(spatial_dims=2, in_channels=3, ...)):
  1. La primera capa de VNet exige 16 % in_channels == 0 (repite el input hasta
     16 canales para la primera conexión residual). Con 3 canales (DWI/ADC/FLAIR)
     esa condición NO se cumple y MONAI lanza ValueError al construir el modelo.
     Aquí se añade un canal de relleno (ceros) para pasar a 4 canales
     (16 % 4 == 0); ese canal no aporta información, es solo para cumplir la
     restricción de la arquitectura.
  2. dropout_dim debe fijarse en 2 explícitamente. Si no, VNet usa su valor por
     defecto (3) y crea capas nn.Dropout3d, que esperan tensores 5D (N,C,D,H,W);
     con nuestros tensores 2D (N,C,H,W) eso fallaría en cuanto el dropout esté
     activo (por defecto SÍ está activo).
  3. NO se pasa dropout_prob explícitamente. En monai==1.6.0 ese argumento del
     constructor de VNet está deprecado: si se le da un único float, MONAI lo
     reenvía a las capas internas de subida (UpTransition), que en esta versión
     esperan una TUPLA (dropout_prob[0], dropout_prob[1]) y no un float, lo que
     provoca 'float' object is not subscriptable. Se deja que VNet use sus
     valores por defecto para esta versión, que sí son válidos.
"""

import torch
import torch.nn as nn
from monai.networks.nets import VNet


class VNet2D(nn.Module):
    """
    Uso igual que los otros 3 modelos del TFM:
        model = VNet2D(in_channels=3, out_channels=1)
    """

    def __init__(self, in_channels=3, out_channels=1):
        super().__init__()
        self.in_channels = in_channels
        self.canales_relleno = 4 - in_channels   # 4 = múltiplo de 16 más próximo hacia arriba
        if self.canales_relleno < 0 or (16 % (in_channels + self.canales_relleno)) != 0:
            raise ValueError("VNet2D está pensado para in_channels en {1,2,3,4}. "
                             "Para otros valores, usa monai.networks.nets.VNet directamente.")
        # dropout_prob NO se pasa (ver nota 3 arriba): se usan los valores por
        # defecto de VNet para esta versión de MONAI.
        self.vnet = VNet(spatial_dims=2, in_channels=in_channels + self.canales_relleno,
                         out_channels=out_channels, dropout_dim=2)

    def forward(self, x):
        if self.canales_relleno > 0:
            B, _, H, W = x.shape
            relleno = torch.zeros(B, self.canales_relleno, H, W, dtype=x.dtype, device=x.device)
            x = torch.cat([x, relleno], dim=1)
        return self.vnet(x)


if __name__ == "__main__":
    # Prueba rápida de formas, incluido el tamaño real tras el remuestreo v2 (144x224).
    # Ejecutar en Colab (necesita torch + monai instalados) antes de lanzar el
    # entrenamiento completo: !python /content/drive/MyDrive/TFM/vnet2d.py
    for H, W in [(256, 256), (144, 224)]:
        m = VNet2D(in_channels=3, out_channels=1)
        x = torch.randn(2, 3, H, W)
        y = m(x)
        assert y.shape == (2, 1, H, W), (H, W, y.shape)
    n_params = sum(p.numel() for p in VNet2D().parameters())
    print("OK: formas correctas en ambos tamaños | parámetros:", f"{n_params:,}")